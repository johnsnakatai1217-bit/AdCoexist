std::string ReadText(const fs::path& aPath)
{
    std::ifstream in(aPath, std::ios::binary);
    return {std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
}

// An archive in the mod folders
struct ModArchive
{
    fs::path path;
    std::string relative; // relative to the game directory
    std::unordered_set<uint64_t> hashes;
};

// The archives loaded by the game, split into mods and vanilla (in group order, which is the priority order)
struct Archives
{
    std::vector<ModArchive> mods;
    std::vector<std::string> vanilla;
    int32_t firstModGroup = -1;
    bool hasEp1 = false;
};

// One ad replaced by one mod
struct Conversion
{
    const ModArchive* mod;
    const AdCatalog::Ad* ad;
    std::vector<const AdCatalog::File*> provided;
    std::string reason; // why it is converted
};

// Reads files by hash from the first archive (in priority order) that contains them
class FileSource
{
public:
    void Add(const fs::path& aArchive, const std::vector<uint64_t>& aHashes)
    {
        for (auto hash : aHashes)
            m_archiveOf.try_emplace(hash, aArchive);
    }

    bool Contains(uint64_t aHash) const
    {
        return m_archiveOf.contains(aHash);
    }

    // Reads all files with the given hashes, opening each archive once
    bool Read(const std::unordered_set<uint64_t>& aHashes, std::unordered_map<uint64_t, Archive::File>& aOut) const
    {
        std::map<fs::path, std::unordered_set<uint64_t>> byArchive;
        for (auto hash : aHashes)
        {
            const auto it = m_archiveOf.find(hash);
            if (it == m_archiveOf.end())
                return false;
            byArchive[it->second].insert(hash);
        }
        for (const auto& [archive, hashes] : byArchive)
        {
            std::vector<Archive::File> files;
            std::string error;
            if (!Archive::Read(archive, files, error, &hashes))
            {
                LOG_ERROR("read %s: %s", archive.string().c_str(), error.c_str());
                return false;
            }
            for (auto& file : files)
                aOut[file.hash] = std::move(file);
        }
        return true;
    }

private:
    std::unordered_map<uint64_t, fs::path> m_archiveOf;
};

// 1. Splits the loaded archives into mods (archive\pc\mod, mods\) and vanilla, without reading them yet
Archives CollectArchives(RED4ext::ResourceDepot* aDepot, const fs::path& aGameDir)
{
    const auto gameDirText = Lower(aGameDir.string()) + "\\";
    const std::string modRoot = gameDirText + "archive\\pc\\mod\\";
    const std::string redmodRoot = gameDirText + "mods\\";

    Archives archives;
    for (uint32_t g = 0; g < aDepot->groups.size(); ++g)
    {
        const auto& group = aDepot->groups[g];
        for (uint32_t a = 0; a < group.archives.size(); ++a)
        {
            const std::string path = group.archives[a].path.c_str();
            const auto lower = Lower(path);
            if (lower.rfind(modRoot, 0) == 0 || lower.rfind(redmodRoot, 0) == 0)
            {
                if (archives.firstModGroup < 0)
                    archives.firstModGroup = static_cast<int32_t>(g);
                archives.mods.push_back({path, path.substr(gameDirText.size()), {}});
            }
            else
            {
                archives.vanilla.push_back(path);
                if (lower.find("\\archive\\pc\\ep1\\") != std::string::npos)
                    archives.hasEp1 = true;
            }
        }
    }
    return archives;
}

// Compares the checksum in the tweakdb.bin header with the catalog and returns the checksum that was read
uint32_t CheckCatalog(const fs::path& aGameDir, bool aHasEp1, bool& aMatches)
{
    const auto& catalog = AdCatalog::Get();
    const auto file = aGameDir / L"r6" / L"cache" / (aHasEp1 ? L"tweakdb_ep1.bin" : L"tweakdb.bin");
    const auto actual = TweakDbFile::ReadChecksum(file);
    const auto expected = aHasEp1 ? catalog.tweakDbEp1Checksum : catalog.tweakDbChecksum;
    aMatches = actual == expected;
    if (!aMatches)
    {
        LOG_WARN("the ad catalog was made for game %s and may be outdated (%s checksum 0x%08x, catalog 0x%08x)",
                 catalog.gameVersion, file.filename().string().c_str(), actual, expected);
    }
    return actual;
}

bool RestoreVanilla(const fs::path& aGameDir)
{
    std::error_code ec;
    return fs::exists(aGameDir / L"red4ext" / L"plugins" / L"AdCoexist" / RestoreVanillaName, ec);
}

// 2. The inputs of this run, written to the manifest
std::string Fingerprint(const Archives& aArchives, uint32_t aTweakDbChecksum, bool aRestoreVanilla)
{
    const auto& catalog = AdCatalog::Get();
    Manifest::Inputs inputs;
    inputs.versionMajor = ADCOEXIST_VERSION_MAJOR;
    inputs.versionMinor = ADCOEXIST_VERSION_MINOR;
    inputs.versionPatch = ADCOEXIST_VERSION_PATCH;
    inputs.catalogGameVersion = catalog.gameVersion;
    inputs.catalogTweakDbChecksum = catalog.tweakDbChecksum;
    inputs.catalogTweakDbEp1Checksum = catalog.tweakDbEp1Checksum;
    inputs.tweakDbChecksum = aTweakDbChecksum;
    inputs.restoreVanilla = aRestoreVanilla;
    for (const auto& mod : aArchives.mods)
    {
        std::error_code ec;
        Manifest::ModStat stat;
        stat.relative = mod.relative;
        stat.size = fs::file_size(mod.path, ec);
        stat.time = fs::last_write_time(mod.path, ec).time_since_epoch().count();
        inputs.mods.push_back(std::move(stat));
    }
    return Manifest::Fingerprint(inputs);
}

Manifest::Outputs CurrentOutputs(const fs::path& aCacheDir)
{
    std::error_code ec;
    Manifest::Outputs outputs;
    outputs.archiveSize = fs::file_size(aCacheDir / ArchiveName, ec);
    outputs.yamlSize = fs::file_size(aCacheDir / YamlName, ec);
    return outputs;
}

// Decides whether to reuse the previous result. If not, aWhyNot tells why
Manifest::Reuse CheckReuse(const fs::path& aCacheDir, const std::string& aFingerprint, std::string& aWhyNot)
{
    std::error_code ec;
    const bool exists = fs::exists(aCacheDir / ArchiveName, ec) && fs::exists(aCacheDir / YamlName, ec);
    const auto manifest = ReadText(aCacheDir / ManifestName);
    const auto outputs = CurrentOutputs(aCacheDir);
    const auto reuse = Manifest::Decide(manifest, aFingerprint, exists, outputs);
    if (reuse == Manifest::Reuse::No)
    {
        aWhyNot = Manifest::ExplainNo(manifest, aFingerprint, exists, outputs);
        LOG_INFO("not reusing the previous result: %s (manifest %u byte(s), archive %llu byte(s), yaml %llu byte(s))",
                 aWhyNot.c_str(), static_cast<unsigned>(manifest.size()),
                 static_cast<unsigned long long>(outputs.archiveSize), static_cast<unsigned long long>(outputs.yamlSize));
    }
    return reuse;
}

// Renames a temporary file to its final name. Logs an error if it fails
bool Commit(const fs::path& aTemp, const fs::path& aPath)
{
    std::error_code ec;
    fs::rename(aTemp, aPath, ec);
    if (ec)
    {
        LOG_ERROR("cannot rename %s to %s (error %d)", aTemp.string().c_str(), aPath.filename().string().c_str(),
                  ec.value());
        return false;
    }
    return true;
}

// Writes a text file through a temporary file. Logs an error if it fails
bool WriteText(const fs::path& aPath, std::string_view aText)
{
    auto temp = aPath;
    temp += L".tmp";
    std::ofstream out(temp, std::ios::binary | std::ios::trunc);
    out.write(aText.data(), static_cast<std::streamsize>(aText.size()));
    out.close();
    if (!out)
    {
        LOG_ERROR("cannot write %s", temp.string().c_str());
        return false;
    }
    return Commit(temp, aPath);
}

bool WriteManifest(const fs::path& aCacheDir, const std::string& aFingerprint, bool aEmpty)
{
    auto outputs = CurrentOutputs(aCacheDir);
    outputs.empty = aEmpty;
    return WriteText(aCacheDir / ManifestName, Manifest::Compose(aFingerprint, outputs));
}

