// Logs a warning or an error and keeps it for the report
void LogProblem(bool aError, const char* aFormat, ...)
{
    va_list args;
    va_start(args, aFormat);
    va_list copy;
    va_copy(copy, args);
    std::string text(static_cast<size_t>(std::max(std::vsnprintf(nullptr, 0, aFormat, copy), 0)), '\0');
    va_end(copy);
    std::vsnprintf(text.data(), text.size() + 1, aFormat, args);
    va_end(args);

    if (aError)
        g_sdk->logger->Error(g_handle, text.c_str());
    else
        g_sdk->logger->Warn(g_handle, text.c_str());
    g_problems.push_back((aError ? "error: " : "warning: ") + text);
}

#define LOG_INFO(...) g_sdk->logger->InfoF(g_handle, __VA_ARGS__)
#define LOG_WARN(...) LogProblem(false, __VA_ARGS__)
#define LOG_ERROR(...) LogProblem(true, __VA_ARGS__)

