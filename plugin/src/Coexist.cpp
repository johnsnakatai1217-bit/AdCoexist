std::string Now()
{
    SYSTEMTIME time{};
    GetLocalTime(&time);
    char text[32];
    std::snprintf(text, sizeof(text), "%04u-%02u-%02u %02u:%02u:%02u", time.wYear, time.wMonth, time.wDay, time.wHour,
                  time.wMinute, time.wSecond);
    return text;
}

// The product version of a loaded DLL, e.g. "1.31.1"
std::string ModuleVersion(const wchar_t* aName)
{
    const auto module = GetModuleHandleW(aName);
    if (!module)
        return "not loaded";
    wchar_t path[MAX_PATH]{};
    GetModuleFileNameW(module, path, MAX_PATH);
    DWORD ignored = 0;
    const auto size = GetFileVersionInfoSizeW(path, &ignored);
    std::vector<uint8_t> data(size);
    VS_FIXEDFILEINFO* info = nullptr;
    UINT length = 0;
    if (size == 0 || !GetFileVersionInfoW(path, 0, size, data.data()) ||
        !VerQueryValueW(data.data(), L"\\", reinterpret_cast<void**>(&info), &length) || !info)
    {
        return "loaded, version unknown";
    }
    return std::to_string(HIWORD(info->dwProductVersionMS)) + "." + std::to_string(LOWORD(info->dwProductVersionMS)) +
           "." + std::to_string(HIWORD(info->dwProductVersionLS));
}

// How the mods were installed. MO2 loads its virtual file system DLL into the game. Vortex puts a marker file in
// the folders it deploys to, so the marker in AdCoexist's own folder means AdCoexist was deployed by Vortex
std::string ModManager()
{
    if (GetModuleHandleW(L"usvfs_x64.dll"))
        return "MO2";
    HMODULE self = nullptr;
    wchar_t path[MAX_PATH]{};
    if (GetModuleHandleExW(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                           reinterpret_cast<LPCWSTR>(&ModManager), &self) &&
        GetModuleFileNameW(self, path, MAX_PATH))
    {
        std::error_code ec;
        if (fs::exists(fs::path(path).parent_path() / L"__folder_managed_by_vortex", ec))
            return "Vortex";
    }
    return "manual";
}

